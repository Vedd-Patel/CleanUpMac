"""
The list of places on a Mac that fill up and can be emptied.

Every entry describes one thing: where it lives, who writes to it, what
happens once it is gone, and how dangerous it is to remove. The scanner
measures these, the web page shows them, and actions.py knows how to clean
them. Nothing in here touches the disk.

Levels
    safe     caches and build output. Regenerated on demand, no data lost.
    careful  real data (media, projects, saves). Gone is gone.
    info     we only show the size. Removal needs the owning app or sudo.

Actions
    ("empty",)          delete everything inside, keep the folder
    ("remove",)         delete the folder itself
    ("run", [...])      run this command, e.g. a tool's own prune
    ("none",)           nothing to do from here, see `how`
"""

